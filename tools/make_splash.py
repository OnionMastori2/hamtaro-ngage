#!/usr/bin/env python3
"""Nokia N-Gage boot screen -> C array (176x208, RGB565).

usage: make_splash.py splash.(jpg|png) out.c
"""
import sys

from PIL import Image


def main():
    src, out = sys.argv[1:3]
    im = Image.open(src).convert('RGB')
    if im.size != (176, 208):
        im = im.resize((176, 208), Image.LANCZOS)
    px = im.load()
    lines = ['/* Generated by tools/make_splash.py from ngage/res/splash_source.jpg.',
             ' * Nokia N-Gage boot screen, 176x208, RGB565, one row per line. */',
             '#include "splash_data.h"', '',
             'const unsigned short g_splash_pixels[SPLASH_H][SPLASH_W] = {']
    for y in range(208):
        row = []
        for x in range(176):
            r, g, b = px[x, y]
            row.append('0x%04X' % (((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)))
        lines.append('    {' + ','.join(row) + '},')
    lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
